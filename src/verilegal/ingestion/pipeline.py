"""Regulation ingestion: verified snapshot → parsed structure → validated chunk JSONL."""

import hashlib
from pathlib import Path

from pydantic import BaseModel

from verilegal.ingestion.chunking import chunk_regulation, validate_chunks, write_chunks_jsonl
from verilegal.ingestion.fetch import load_manifest
from verilegal.ingestion.regulation_parser import check_structure, parse_regulation_file
from verilegal.ingestion.sources import get_source


class IngestionError(RuntimeError):
    """Raised when a snapshot is missing or does not match its manifest."""


class IngestStats(BaseModel):
    """Outcome of ingesting one regulation, used for the sanity report."""

    key: str
    regulation: str
    articles: int
    expected_articles: int
    recitals: int
    expected_recitals: int
    parent_chunks: int
    child_chunks: int
    recital_chunks: int
    split_children: int  # children produced by splitting an oversized paragraph per point
    oversized_chunks: int  # chunks still longer than max_chars (single long blocks)
    max_chunk_chars: int
    output: str | None
    problems: list[str]

    @property
    def ok(self) -> bool:
        """True when the structure matches the official counts and chunks are valid."""
        return not self.problems


def processed_path(processed_dir: Path, key: str, lang: str) -> Path:
    """Location of the chunk JSONL for one regulation."""
    return processed_dir / f"{key}.{lang}.jsonl"


def ingest_regulation(
    key: str, lang: str, raw_dir: Path, processed_dir: Path, *, max_chars: int
) -> IngestStats:
    """Parse and chunk one fetched regulation; write JSONL only when every check passes."""
    source = get_source(key)
    record = load_manifest(raw_dir, lang).snapshots.get(key)
    if record is None:
        raise IngestionError(f"{source.name}: no {lang} snapshot; run `verilegal fetch` first")
    snapshot = raw_dir / record.file
    if not snapshot.exists():
        raise IngestionError(f"{source.name}: snapshot file {snapshot} is missing")
    if hashlib.sha256(snapshot.read_bytes()).hexdigest() != record.sha256:
        raise IngestionError(f"{source.name}: {snapshot} does not match its manifest sha256")

    parsed = parse_regulation_file(snapshot)
    chunks = chunk_regulation(
        parsed,
        doc_id=source.celex,
        name=source.name,
        lang=lang,
        max_chars=max_chars,
        celex=source.celex,
        source_url=source.eurlex_url(lang),
    )
    problems = check_structure(parsed, source) + validate_chunks(chunks)

    children = [c for c in chunks if c.role == "child" and c.doc_type == "regulation_article"]
    output = None
    if not problems:
        path = processed_path(processed_dir, key, lang)
        write_chunks_jsonl(chunks, path)
        output = path.as_posix()

    return IngestStats(
        key=key,
        regulation=source.name,
        articles=len(parsed.articles),
        expected_articles=source.expected_articles,
        recitals=len(parsed.recitals),
        expected_recitals=source.expected_recitals,
        parent_chunks=sum(c.role == "parent" for c in chunks),
        child_chunks=len(children),
        recital_chunks=sum(c.doc_type == "recital" for c in chunks),
        split_children=sum("_pt" in c.chunk_id or "_al" in c.chunk_id for c in children),
        oversized_chunks=sum(len(c.text) > max_chars for c in chunks if c.role == "child"),
        max_chunk_chars=max_chars,
        output=output,
        problems=problems,
    )


def render_sanity_report(stats: list[IngestStats], lang: str) -> str:
    """Markdown summary comparing parsed structure with the official tables of contents."""
    lines = [
        f"# Regulation ingestion sanity report ({lang})",
        "",
        "Generated by `verilegal ingest regulations`. Expected counts are the official "
        "numbers of articles and recitals.",
        "",
        "| Regulation | Articles (parsed / official) | Recitals (parsed / official) "
        "| Parent chunks | Child chunks | Split per point | Oversized | Status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in stats:
        lines.append(
            f"| {s.regulation} | {s.articles} / {s.expected_articles} "
            f"| {s.recitals} / {s.expected_recitals} | {s.parent_chunks} | {s.child_chunks} "
            f"| {s.split_children} | {s.oversized_chunks} | {'OK' if s.ok else 'FAILED'} |"
        )
    max_chars = stats[0].max_chunk_chars if stats else 0
    lines += [
        "",
        f"*Oversized* = child or recital chunks still longer than {max_chars} characters "
        "(a single long block that cannot be split per point).",
    ]
    problems = [p for s in stats for p in s.problems]
    if problems:
        lines += ["", "## Problems", "", *[f"- {p}" for p in problems]]
    return "\n".join(lines) + "\n"
